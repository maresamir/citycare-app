                ),
              );
              FFAppState().reportes = [];
              safeSetState(() {});
              await actions.guardarTokenSeguro(
                '',
              );
              FFAppState().tokenSesion = '';
              safeSetState(() {});
              FFAppState().sesionIniciada = false;
              safeSetState(() {});

              context.pushNamed(IniciarSesionWidget.routeName);
            }
          }
        }
      }
    });

    WidgetsBinding.instance.addPostFrameCallback((_) => safeSetState(() {}));
